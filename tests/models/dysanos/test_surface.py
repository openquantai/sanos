from __future__ import annotations

from dataclasses import replace

import numpy as np
import pytest
import torch

from sanos.models.dysanos.config import DailyFrontGeometryConfig
from sanos.models.dysanos.dynamics import NativeDailyModel
from sanos.models.dysanos.surface import (
    SanosSurfaceDecoder,
    bound_native_state,
    inner_nms_nodes,
    native_state_width,
    raw_from_parameters,
    shared_nms_node_sets,
)


def _geometry() -> DailyFrontGeometryConfig:
    return replace(
        DailyFrontGeometryConfig(),
        model_business_dtes=(1.0, 5.0, 10.0),
        num_inner_strikes=10,
    )


def test_canonical_geometry_and_native_parameter_round_trip() -> None:
    geometry = _geometry()
    nodes = inner_nms_nodes(200, (-3.0, 2.0))
    front, final = shared_nms_node_sets(200, (-3.0, 2.0))
    assert nodes.shape == (200,)
    assert front.shape == final.shape == (100,)
    assert np.count_nonzero(front == 0.0) == 1
    assert not np.any(np.isclose(final, 0.0, atol=1.0e-14, rtol=0.0))

    raw = NativeDailyModel(
        2,
        geometry,
        torch.zeros((2, native_state_width(geometry)), dtype=torch.float64),
        dtype=torch.float64,
    ).raw_states.detach()
    parameters = bound_native_state(raw, geometry)
    replay = bound_native_state(raw_from_parameters(parameters, geometry), geometry)
    torch.testing.assert_close(replay.dlv_squares, parameters.dlv_squares)
    torch.testing.assert_close(replay.forward_volatilities, parameters.forward_volatilities)
    torch.testing.assert_close(replay.eta, parameters.eta)
    assert native_state_width(geometry) == 3 * 12


def test_surface_is_a_differentiable_martingale_and_prices_zero_time() -> None:
    geometry = _geometry()
    model = NativeDailyModel(
        2,
        geometry,
        torch.zeros((2, native_state_width(geometry)), dtype=torch.float64),
        dtype=torch.float64,
    )
    decoder = SanosSurfaceDecoder(geometry, dtype=torch.float64)
    surface = decoder(bound_native_state(model.raw_states, geometry))

    torch.testing.assert_close(
        surface.densities.sum(dim=-1), torch.ones((2, 3), dtype=torch.float64)
    )
    torch.testing.assert_close(
        (surface.support_strikes * surface.densities).sum(dim=-1),
        torch.ones((2, 3), dtype=torch.float64),
    )
    assert float(surface.densities.detach().min()) >= -1.0e-12
    assert torch.all(torch.diff(surface.total_volatilities, dim=-1) > 0.0)

    expiries = torch.tensor(
        [[0.0, 5.0 / 252.0], [0.0, 10.0 / 252.0]], dtype=torch.float64
    )
    strikes = torch.tensor([[0.9, 1.0], [1.1, 1.2]], dtype=torch.float64)
    prices = decoder.price_calls(surface, expiries, strikes)
    torch.testing.assert_close(prices[:, 0], torch.relu(1.0 - strikes[:, 0]))
    prices.sum().backward()
    assert model.raw_states.grad is not None
    assert bool(torch.all(torch.isfinite(model.raw_states.grad)))


def test_shared_geometry_rejects_noncanonical_inner_count() -> None:
    geometry = replace(_geometry(), num_inner_strikes=11)
    with pytest.raises(ValueError, match="even"):
        SanosSurfaceDecoder(geometry)


def test_support_epsilon_is_an_explicit_model_geometry_parameter() -> None:
    geometry = _geometry()
    wider_epsilon = replace(geometry, support_epsilon_business_dte=0.25)
    raw = torch.zeros((1, native_state_width(geometry)), dtype=torch.float64)
    default_surface = SanosSurfaceDecoder(geometry, dtype=torch.float64)(
        bound_native_state(raw, geometry)
    )
    wider_surface = SanosSurfaceDecoder(wider_epsilon, dtype=torch.float64)(
        bound_native_state(raw, wider_epsilon)
    )
    assert not torch.equal(default_surface.support_strikes, wider_surface.support_strikes)


